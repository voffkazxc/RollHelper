def simulate_ahk_pickup_extract(workComment: str):
    if not re.search(r'(?i)(?<![\wа-яА-ЯіїєґІЇЄҐёЁ])(Самовивіз|Самовывоз|Самовынос)(?![\wа-яА-ЯіїєґІЇЄҐёЁ])', workComment):
        return False, ""
    
    stopPat = r'(?=\s*(?:Знижка|Скидка|Доставка|Прибори|Приборы|Купон|Подарунок|Подарок|Найближчим|Ближайш|\d{4}-\d{2}|\b(?:Фоп|ФОП|FOP)\b|\||$))'
    pickupPoint = ""

    # 1. Colons / dashes
    matches1 = re.findall(r'(?i)(?<!Знижка\s)(?<!Скидка\s)(?:Самовивіз|Самовывоз|Самовынос)\s*[:\-—]\s*([^\r\n|]+?)' + stopPat, workComment)
    for cand in reversed(matches1):
        cand = cand.strip(" \t,.-–—")
        if cand and not re.match(r'(?i)^(?:\d{1,2}:\d{2}|Найближчим|Ближайш|Прибори|Приборы|Купон|Подарунок|Подарок)', cand):
            pickupPoint = cand
            break

    # 2. Spaces without colon
    if not pickupPoint:
        matches2 = re.findall(r'(?i)(?<!Знижка\s)(?<!Скидка\s)(?:Самовивіз|Самовывоз|Самовынос)\s+([^\r\n|]+?)' + stopPat, workComment)
        for cand in reversed(matches2):
            cand = cand.strip(" \t,.-–—")
            if cand and not re.match(r'(?i)^(?:\d{1,2}:\d{2}|Найближчим|Ближайш|Прибори|Приборы|Купон|Подарунок|Подарок)', cand):
                pickupPoint = cand
                break

    return True, pickupPoint

