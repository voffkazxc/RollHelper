# Дозволи по ролях: role → set of permissions
ROLE_PERMS: dict[str, set] = {
    'manager':  {'delete_order', 'block_customer', 'manage_settings', 'set_pin', 'create_order', 'edit_order', 'change_status', 'assign_courier', 'manage_couriers'},
    'operator': {'create_order', 'edit_order', 'change_status', 'assign_courier'},
    'courier':  {'view_own_orders'},
    'system':   {'*'},
}


def err(code: str, extra: dict | None = None) -> dict:
    """
    Повертає стандартний error dict за кодом.
    Якщо код не зареєстровано — fallback із кодом (не «Щось пішло не так»).

    >>> err('ORDER_NOT_FOUND')
    {'ok': False, 'error': '...', 'error_code': 'ORDER_NOT_FOUND', 'action': '...'}
    """
    entry = _REGISTRY.get(code)
    if entry:
        msg, action = entry
    else:
        msg    = f'Помилка [{code}].'
        action = 'Зафіксуйте код помилки і передайте розробнику.'
    result: dict = {'ok': False, 'error': msg, 'error_code': code, 'action': action}
    if extra:
        result.update(extra)
    return result


def check_role(actor_role: str, required_perm: str) -> bool:
    """
    Повертає True якщо роль має дозвіл.
    P8: перевірка завжди на сервері.
    """
    perms = ROLE_PERMS.get(actor_role, set())
    return '*' in perms or required_perm in perms
